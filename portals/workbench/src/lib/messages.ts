/** Translate interface copy without changing user or product content. */
export function translate(
  locale: Locale,
  message: string,
  ...values: string[]
): string {
  const favorite = /^(已取消收藏|已收藏)(.+)$/u.exec(message);
  if (favorite && values.length === 0)
    return translate(locale, `${favorite[1]}{0}`, favorite[2]!);
  const text = locale === "en-US" ? (EN_MESSAGES[message] ?? message) : message;
  return text.replace(
    /\{(\d+)\}/g,
    (_, index: string) => values[Number(index)] ?? `{${index}}`,
  );
}
